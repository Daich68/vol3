const MEMORY_KEY = "voltri.catSaid";
const MEMORY = 30;

function said(): string[] {
    try {
        return JSON.parse(sessionStorage.getItem(MEMORY_KEY) || "[]");
    } catch {
        return [];
    }
}

function remember(line: string) {
    try {
        sessionStorage.setItem(MEMORY_KEY, JSON.stringify([line, ...said()].slice(0, MEMORY)));
    } catch {
        // she forgets, no harm done
    }
}

// a line from the pool she has not said lately; the pool is never exhausted — memory is shorter than it
export function chatter(key: ChatterKey, vars: Record<string, string | undefined> = {}): string | null {
    const pool = LINES[key].filter((line) => !/\{(\w+)\}/.test(line) || Array.from(line.matchAll(/\{(\w+)\}/g)).every((m) => vars[m[1]]));
    if (pool.length === 0) return null;
    const recent = said();
    const fresh = pool.filter((line) => !recent.includes(line));
    const source = fresh.length > 0 ? fresh : pool;
    const line = source[Math.floor(Math.random() * source.length)];
    remember(line);
    return line.replace(/\{(\w+)\}/g, (_, k) => vars[k] || "");
}

export function timeOfDayKey(): ChatterKey {
    const h = new Date().getHours();
    if (h < 5) return "night";
    if (h < 11) return "morning";
    if (h >= 19) return "evening";
    return "idle";
}

